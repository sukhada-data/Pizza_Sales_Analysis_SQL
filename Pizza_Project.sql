-- 9. What is the average monthly revenue, and how does it vary by category?
WITH Average_Monthly_Revenue AS
(
    SELECT
        YEAR(o.date) AS Order_Year,
        MONTH(o.date) AS Order_Month,
        pt.category,
        SUM(p.price * od.quantity) AS Monthly_Revenue
    FROM pizza_types pt
    JOIN pizzas p
        ON pt.pizza_type_id = p.pizza_type_id
    JOIN order_details od
        ON od.pizza_id = p.pizza_id
    JOIN orders o
        ON od.order_id = o.order_id
    GROUP BY
        YEAR(o.date),
        MONTH(o.date),
        pt.category
)
SELECT
    Order_Month,
    CAST(AVG(CASE WHEN category = 'Chicken' THEN Monthly_Revenue END) AS DECIMAL(10,2)) AS Chicken,
    CAST(AVG(CASE WHEN category = 'Classic' THEN Monthly_Revenue END) AS DECIMAL(10,2)) AS Classic,
    CAST(AVG(CASE WHEN category = 'Supreme' THEN Monthly_Revenue END) AS DECIMAL(10,2)) AS Supreme,
    CAST(AVG(CASE WHEN category = 'Veggie' THEN Monthly_Revenue END) AS DECIMAL(10,2)) AS Veggie
FROM Average_Monthly_Revenue
GROUP BY Order_Month
ORDER BY Order_Month;


WITH Category_Monthly_Revenue AS
(
    SELECT
        YEAR(o.date) AS Order_Year,
        MONTH(o.date) AS Order_Month,
        pt.category,
        CAST(SUM(p.price * od.quantity) AS DECIMAL(10, 2)) AS Monthly_Revenue
    FROM pizza_types pt
    JOIN pizzas p
        ON pt.pizza_type_id = p.pizza_type_id
    JOIN order_details od
        ON od.pizza_id = p.pizza_id
    JOIN orders o
        ON od.order_id = o.order_id
    GROUP BY
        YEAR(o.date),
        MONTH(o.date),
        pt.category
),
Average_Monthly_Revenue AS
(
    SELECT
        Order_Month,
        category,
        CAST(AVG(Monthly_Revenue) AS DECIMAL(10, 2)) AS Average_Monthly_Revenue
    FROM Category_Monthly_Revenue
    GROUP BY
        Order_Month,
        category
)
SELECT *
FROM
(
    SELECT
        Order_Month,
        category,
        CAST(Average_Monthly_Revenue AS DECIMAL(10,2)) AS Average_Monthly_Revenue
    FROM Average_Monthly_Revenue
) AS SourceTable
PIVOT
(
    AVG(Average_Monthly_Revenue)
    FOR category IN ([Chicken], [Classic], [Supreme], [Veggie])
) AS PivotTable
ORDER BY Order_Month;


