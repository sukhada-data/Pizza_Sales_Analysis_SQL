    ON p1.pizza_type_id = pt1.pizza_type_id
JOIN pizza_types pt2
    ON p2.pizza_type_id = pt2.pizza_type_id
GROUP BY
    pt1.name,
    pt2.name
ORDER BY
    Times_Ordered_Together DESC;


