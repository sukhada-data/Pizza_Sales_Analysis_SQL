-- Sales Performance
-- 1. What is the total revenue generated by the company?
SELECT CAST(SUM(p.price * od.quantity) AS DECIMAL(10, 2)) AS 'Total Revenue'
FROM pizzas p
JOIN order_details od 
	ON p.pizza_id = od.pizza_id;


-- 2. We want to know which pizzas are performing well and which aren’t. Break down
-- sales performance by type, size, and category.
SELECT p.pizza_type_id,
	   pt.name, 
	   p.size, 
	   pt.category,
	   SUM(od.quantity) AS Total_Quantity_Sold,
	   CAST(SUM(p.price * od.quantity) AS DECIMAL(10, 2)) AS Total_Revenue
FROM pizza_types pt
JOIN pizzas p 
	ON p.pizza_type_id = pt.pizza_type_id
JOIN order_details od 
	ON od.pizza_id = p.pizza_id
GROUP BY p.pizza_type_id, 
		 pt.name, 
		 p.size, 
		 pt.category
ORDER BY Total_Revenue DESC;


-- 3. Which pizza type, size, and category generate the highest and lowest revenue?
WITH pizza_info AS 
            (
                SELECT p.pizza_type_id,
                       pt.name,
                       p.size, 
                       pt.category,
                       CAST(SUM(p.price * od.quantity) AS DECIMAL(10, 2)) AS Total_Revenue
                FROM pizza_types pt
                JOIN pizzas p 
                    ON p.pizza_type_id = pt.pizza_type_id
                JOIN order_details od 
                    ON od.pizza_id = p.pizza_id
                GROUP BY p.pizza_type_id,  
                            pt.name,
                            p.size, 
                            pt.category
			) 
SELECT pizza_type_id,
	   name,
       size,
       category,
	   Total_Revenue,
       CASE
            WHEN Highest_Revenue = 1 THEN 'High Revenue'
            WHEN Lowest_Revenue = 1 THEN 'Low Revenue'
       END AS Revenue_Rank
FROM (
		SELECT *,
			RANK() OVER(ORDER BY Total_Revenue DESC) AS Highest_Revenue, 
			RANK() OVER(ORDER BY Total_Revenue ASC) AS Lowest_Revenue
FROM pizza_info
	 ) AS ranks
WHERE Highest_Revenue = 1 
	  OR Lowest_Revenue = 1;


-- 4. Identify the top-performing and underperforming pizzas to evaluate potential menu adjustments.
WITH pizza_performance AS
            (
                SELECT
                    p.pizza_type_id,
                    pt.name,
                    p.size,
                    pt.category,
                    SUM(od.quantity) AS Total_Quantity_Sold,
                    CAST(SUM(p.price * od.quantity) AS DECIMAL(10,2)) AS Total_Revenue
                FROM pizza_types pt
                JOIN pizzas p
                    ON pt.pizza_type_id = p.pizza_type_id
                JOIN order_details od
                    ON p.pizza_id = od.pizza_id
                GROUP BY
                    p.pizza_type_id,
                    pt.name,
                    p.size,
                    pt.category
            ),
Ranked_Pizzas AS
    (
    SELECT *,
           RANK() OVER(ORDER BY Total_Revenue DESC) AS Top_Rank,
           RANK() OVER(ORDER BY Total_Revenue ASC) AS Bottom_Rank
    FROM pizza_performance
    )
SELECT
    pizza_type_id,
    name,
    size,
    category,
    Total_Quantity_Sold,
    Total_Revenue,
    CASE
        WHEN Top_Rank <= 5 THEN 'Top Performing'
        WHEN Bottom_Rank <= 5 THEN 'Underperforming'
    END AS Performance
FROM Ranked_Pizzas
WHERE Top_Rank <= 5
   OR Bottom_Rank <= 5
ORDER BY Total_Revenue DESC;


