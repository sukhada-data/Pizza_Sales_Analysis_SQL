-- Generate a summary of peak order times for each day of the week for scheduling staff shifts more effectively.
WITH HourlyOrders AS
(
    SELECT
        DATENAME(WEEKDAY, date) AS Day_Name,
        DATEPART(HOUR, time) AS Order_Hour,
        COUNT(*) AS Total_Orders
    FROM orders
    GROUP BY
        DATENAME(WEEKDAY, date),
        DATEPART(HOUR, time)
),
RankedHours AS
(
    SELECT *,
           ROW_NUMBER() OVER (PARTITION BY Day_Name ORDER BY Total_Orders DESC) AS rn
    FROM HourlyOrders
)
SELECT
    Day_Name,
    Order_Hour,
    Total_Orders
FROM RankedHours
WHERE rn = 1
ORDER BY
CASE Day_Name
    WHEN 'Monday' THEN 1
    WHEN 'Tuesday' THEN 2
    WHEN 'Wednesday' THEN 3
    WHEN 'Thursday' THEN 4
    WHEN 'Friday' THEN 5
    WHEN 'Saturday' THEN 6
    WHEN 'Sunday' THEN 7
END;


