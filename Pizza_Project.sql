-- 25. Which ingredients are the most and least utilized based on current trends?
WITH IngredientUsage AS
(
    SELECT
        LTRIM(RTRIM(i.value)) AS Ingredient,
        SUM(od.quantity) AS Total_Required
    FROM pizza_types pt
    JOIN pizzas p
        ON pt.pizza_type_id = p.pizza_type_id
    JOIN order_details od
        ON p.pizza_id = od.pizza_id
    CROSS APPLY STRING_SPLIT(pt.ingredients, ',') AS i
    GROUP BY LTRIM(RTRIM(i.value))
)
SELECT *
FROM
(
    SELECT TOP 2
        Ingredient,
        Total_Required,
        'Most Utilized' AS Utilization
    FROM IngredientUsage
    ORDER BY Total_Required DESC
) AS MostUsed

UNION ALL

SELECT *
FROM
(
    SELECT TOP 2
        Ingredient,
        Total_Required,
        'Least Utilized' AS Utilization
    FROM IngredientUsage
    ORDER BY Total_Required ASC
) AS LeastUsed;


-- 26. What are the monthly requirements for the top 3 most used ingredients?
WITH TopIngredients AS
(
    SELECT TOP 3
        LTRIM(RTRIM(s.value)) AS Ingredient
    FROM pizza_types pt
    JOIN pizzas p
        ON pt.pizza_type_id = p.pizza_type_id
    JOIN order_details od
        ON p.pizza_id = od.pizza_id
    CROSS APPLY STRING_SPLIT(pt.ingredients, ',') s
    GROUP BY LTRIM(RTRIM(s.value))
    ORDER BY SUM(od.quantity) DESC
)

SELECT
    LTRIM(RTRIM(s.value)) AS Ingredient,
    DATENAME(MONTH, o.date) AS Month_Name,
    MONTH(o.date) AS Month_No,
    SUM(od.quantity) AS Total_Required
FROM pizza_types pt
JOIN pizzas p
    ON pt.pizza_type_id = p.pizza_type_id
JOIN order_details od
    ON p.pizza_id = od.pizza_id
JOIN orders o
    ON o.order_id = od.order_id
CROSS APPLY STRING_SPLIT(pt.ingredients, ',') s
WHERE LTRIM(RTRIM(s.value)) IN
(
    SELECT Ingredient
    FROM TopIngredients
)
GROUP BY
    LTRIM(RTRIM(s.value)),
    DATENAME(MONTH, o.date),
    MONTH(o.date)
ORDER BY
    Ingredient,
    Month_No;


-- 27. Help us optimize our ingredient supply chain. Which ingredients are used most frequently, and what are the monthly requirements?
WITH IngredientUsage AS
(
    SELECT
        LTRIM(RTRIM(s.value)) AS Ingredient,
        SUM(od.quantity) AS Total_Used
