    FROM orders o
    JOIN order_details od
        ON o.order_id = od.order_id
    JOIN pizzas p
        ON od.pizza_id = p.pizza_id
    GROUP BY o.order_id
)
SELECT
    CAST(AVG(Order_Value) AS DECIMAL(10,2)) AS Average_Order_Value
