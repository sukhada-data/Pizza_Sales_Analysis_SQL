    CAST(AVG(Total_Items) AS DECIMAL(10,2)) AS Average_Pizzas_Per_Order
FROM
(
    SELECT
        order_id,
        SUM(quantity) AS Total_Items
    FROM order_details
    GROUP BY order_id
) t;

-- Large vs Small Orders
SELECT
    CASE
        WHEN Total_Items <= 2 THEN 'Small Order'
        WHEN Total_Items BETWEEN 3 AND 5 THEN 'Medium Order'
        ELSE 'Large Order'
    END AS Order_Size,
    COUNT(*) AS Number_of_Orders
FROM
(
    SELECT
        order_id,
        SUM(quantity) AS Total_Items
    FROM order_details
    GROUP BY order_id
) t
GROUP BY
    CASE
        WHEN Total_Items <= 2 THEN 'Small Order'
        WHEN Total_Items BETWEEN 3 AND 5 THEN 'Medium Order'
        ELSE 'Large Order'
    END;

-- Weekday vs Weekend Orders
SELECT
    CASE
        WHEN DATENAME(WEEKDAY, date) IN ('Saturday','Sunday')
            THEN 'Weekend'
        ELSE 'Weekday'
    END AS Order_Type,
    COUNT(*) AS Total_Orders
FROM orders
GROUP BY
    CASE
        WHEN DATENAME(WEEKDAY, date) IN ('Saturday','Sunday')
            THEN 'Weekend'
        ELSE 'Weekday'
    END;


